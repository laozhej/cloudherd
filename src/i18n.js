const DICTS = { en: EN, zh: ZH };
let lang = 'en';
export const setLang = (l) => { lang = DICTS[l] ? l : 'en'; return lang; };
export const getLang = () => lang;
export const detectLang = () => (/^zh/i.test(navigator.language || '') ? 'zh' : 'en');
export function t(key, vars) {
  let s = DICTS[lang][key] ?? EN[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
  return s;
}
export function missingKeys() {
  const out = [];
  for (const k of Object.keys(EN)) if (!(k in ZH)) out.push('zh:' + k);
  for (const k of Object.keys(ZH)) if (!(k in EN)) out.push('en:' + k);
  return out;
}
